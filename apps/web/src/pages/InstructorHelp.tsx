import Breadcrumb from '../components/Breadcrumb';
import { useAuth } from '../lib/auth';

/**
 * 使い方ガイドの「講師編」（issue #63, #66）。issue #66 でフッターに移し、
 * 生徒編（StudentHelp）・講師編の2ページに分割した。講師向けの操作説明は誰でも
 * 閲覧できるようにし、管理者専用の運用（招待管理・パスキー復旧・削除済み小説）だけ
 * is_admin のときに追加表示する。
 */
export default function InstructorHelp() {
  const { state } = useAuth();
  const isAdmin = state.status === 'authenticated' && state.user.isAdmin;

  return (
    <main className="page">
      <Breadcrumb items={[{ label: 'ホーム', to: '/' }, { label: '講師の使い方' }]} />
      <h1>講師の使い方</h1>
      <p>
        講師資格（can_teach）があると、新しい講座を作成できます。作成・参加した講座ごとに講師/生徒の役割を持ち、
        ある講座では講師、別の講座では生徒、ということもあります。生徒としての操作は「生徒の使い方」を参照してください。
      </p>

      <h2>講座の作成</h2>
      <p>
        「講座一覧」の「講座を作成」から新しい講座を作れます。作成すると、自分は自動的にその講座の
        講師（参加中）になります。
      </p>

      <h2>生徒を講座に加える2つの方法</h2>
      <p className="notice">生徒を講座に加える方法は2つあり、区別が分かりにくいので注意してください。</p>
      <p>
        <strong>① 講師からの招待</strong>: 講座詳細ページの「生徒を招待」フォームに氏名・メールアドレスを
        入力し「招待URLを発行」を押すと、招待URLが表示されます。このURLは自動送信されないので、
        自分でコピーして本人にメール等で伝えてください。相手が招待URLからパスキー登録を済ませると、
        <strong>講師の承認なしに</strong>即座にその講座の生徒（参加中）になります。
      </p>
      <p>
        <strong>② 生徒からの参加申請</strong>: 生徒が自分で「参加申請」した場合は、講座詳細ページの
        「メンバー」一覧に「承認待ち」として表示されます。そこで「承認」または「拒否」を選んでください。
        こちらは①と違い、<strong>講師の承認が必要</strong>です。
      </p>

      <h2>講座の運営</h2>
      <p>
        発行した招待は「発行済みの招待」一覧で確認・失効でき、講座の状態（オープン/クローズ/クローズ・
        閲覧のみ）も講座詳細ページから切り替えられます。また、その講座の小説に対してコメントを投稿したり、
        課題・お知らせを作成したりできます。
      </p>

      {isAdmin && (
        <>
          <h2>管理者としての操作</h2>
          <p className="notice">
            「招待管理」画面の招待は、講座の「生徒を招待」とは別物です。混同しないよう注意してください。
          </p>
          <p>
            <strong>講座の「生徒を招待」</strong>（講師も利用可）は、特定の講座の生徒としての参加を作ります。
          </p>
          <p>
            <strong>「招待管理」画面</strong>（管理者専用、講座に紐付かない招待）は、新しいアカウントを作り、
            管理者権限・講師資格の付与を行うためのものです。どの講座にも所属させません。生徒を特定の講座に
            招待したい場合は、必ずその講座の詳細ページから招待してください。
          </p>
          <p>
            <strong>「ユーザー管理」画面</strong>では、登録済みユーザーの講師資格の付与・はく奪と、管理者権限の
            付与ができます。管理者権限のはく奪は画面からはできず、運用スクリプト（<code>npm run revoke:admin</code>）で
            行います。
          </p>
          <p>
            「パスキー管理」画面内の「ユーザーのパスキー管理」から、全ユーザーの一覧確認と、パスキーを
            すべて失ったユーザーの手動復旧（既存パスキーの失効 →
            再登録用の招待URLを発行）ができます。この再登録招待は新しいアカウントを作らず、既存のアカウントに
            パスキーを追加するだけなので、講座への参加状況や投稿済みの小説はそのまま引き継がれます。
          </p>
          <p>
            「削除済み小説」画面では、論理削除された小説を著者・講座・削除者・削除コメント付きで確認できます
            （削除された小説は、削除した管理者以外には著者本人であっても見えなくなります）。
          </p>
        </>
      )}
    </main>
  );
}
