import Breadcrumb from '../components/Breadcrumb';
import { useAuth } from '../lib/auth';

/**
 * 使い方ガイド（issue #63）。Mckoyは固定のroleを持たず、is_admin・can_teach・
 * 講座ごとのmembershipという直交する権限の組み合わせで動くため、ページを
 * 役割別に分けるのではなく1つのページ内で自分に関係あるセクションだけを
 * 出し分ける（管理者かつ講師、といった兼務もそのまま表示される）。
 */
export default function Help() {
  const { state } = useAuth();
  if (state.status !== 'authenticated') return null;
  const { user } = state;

  return (
    <main className="page">
      <Breadcrumb items={[{ label: 'ホーム', to: '/' }, { label: '使い方' }]} />
      <h1>使い方</h1>
      <p>
        Mckoyでは、「管理者」「講師資格」「各講座での参加状況（講師/生徒、承認待ち/参加中）」の組み合わせで
        できることが決まります。固定の役職ではないため、ある講座では講師、別の講座では生徒、ということもあります。
        以下はあなたの現在の権限に応じて表示しています。
      </p>

      <h2>生徒として</h2>
      <p>
        管理者または講師から届いた招待URLを開き、「パスキーを登録」するとアカウントが作られ、そのままログイン状態になります。
        招待URLは7日間有効で、一度使うと使えなくなります。
      </p>
      <p>
        ログイン後は、ホーム画面の「講座一覧」から、既に参加している講座を確認できます。まだ参加していない
        講座（オープン状態のもの）には「参加申請」ボタンから申請できますが、これは即座に参加できるわけではなく、
        その講座の講師が「承認」するまでは「承認待ち」のままで、小説などは見られません。
      </p>
      <p>
        参加中の講座では、小説の投稿・閲覧、講師からのコメント確認、課題・お知らせの確認ができます。講座が
        「クローズ」の間は講座名とお知らせ以外は見られなくなり、「クローズ・閲覧のみ」の間は閲覧はできますが、
        新しい小説の投稿や、自分の小説の編集・削除はできません。
      </p>
      <p>
        「パスキー管理」画面から、ログインに使う端末（パスキー）を追加登録できます。登録済みのパスキーが
        1件だけの場合は、削除するとログインできなくなるため削除ボタンは表示されません。
      </p>

      {user.canTeach && (
        <>
          <h2>講師として</h2>
          <p>
            「講座一覧」の「講座を作成」から新しい講座を作れます。作成すると、自分は自動的にその講座の
            講師（参加中）になります。
          </p>
          <p className="notice">
            生徒を講座に加える方法は2つあり、区別が分かりにくいので注意してください。
          </p>
          <p>
            <strong>① 講師からの招待</strong>: 講座詳細ページの「生徒を招待」フォームに氏名・メールアドレスを
            入力し「招待URLを発行」を押すと、招待URLが表示されます。このURLは自動送信されないので、
            自分でコピーして本人にメール等で伝えてください。相手が招待URLからパスキー登録を済ませると、
            <strong>講師の承認なしに</strong>即座にその講座の生徒（参加中）になります。
          </p>
          <p>
            <strong>② 生徒からの参加申請</strong>: 生徒が自分で「参加申請」した場合は、講座詳細ページの
            「メンバー」一覧に「承認待ち」として表示されます。そこで「承認」または「拒否」を選んでください。
            こちらは①と違い、<strong>講師の承認が必要</strong>です。
          </p>
          <p>
            発行した招待は「発行済みの招待」一覧で確認・失効でき、講座の状態（オープン/クローズ/クローズ・
            閲覧のみ）も講座詳細ページから切り替えられます。また、その講座の小説に対してコメントを投稿したり、
            課題・お知らせを作成したりできます。
          </p>
        </>
      )}

      {user.isAdmin && (
        <>
          <h2>管理者として</h2>
          <p className="notice">
            「招待管理」画面の招待は、講座の「生徒を招待」とは別物です。混同しないよう注意してください。
          </p>
          <p>
            <strong>講座の「生徒を招待」</strong>（講師も利用可）は、特定の講座の生徒としての参加を作ります。
          </p>
          <p>
            <strong>「招待管理」画面</strong>（管理者専用、講座に紐付かない招待）は、新しいアカウントを作り、
            管理者権限・講師資格の付与を行うためのものです。どの講座にも所属させません。生徒を特定の講座に
            招待したい場合は、必ずその講座の詳細ページから招待してください。
          </p>
          <p>
            「パスキー管理」画面内の「ユーザーのパスキー管理」から、全ユーザーの一覧確認と、パスキーを
            すべて失ったユーザーの手動復旧（既存パスキーの失効 →
            再登録用の招待URLを発行）ができます。この再登録招待は新しいアカウントを作らず、既存のアカウントに
            パスキーを追加するだけなので、講座への参加状況や投稿済みの小説はそのまま引き継がれます。
          </p>
          <p>
            「削除済み小説」画面では、論理削除された小説を著者・講座・削除者・削除コメント付きで確認できます
            （削除された小説は、削除した管理者以外には著者本人であっても見えなくなります）。
          </p>
        </>
      )}
    </main>
  );
}
